export type LinkinParkSong = {
  id: string;
  title: string;
  album: string;
  aliases: string[];
  /** Short fair-use lyric lines for the lyrics quiz. Optional for audio-only / instrumental tracks. */
  lyrics?: string[];
};

function song(
  id: string,
  title: string,
  album: string,
  opts?: { aliases?: string[]; lyrics?: string[] },
): LinkinParkSong {
  return {
    id,
    title,
    album,
    aliases: opts?.aliases?.length
      ? opts.aliases
      : [title.toLowerCase().replace(/[^a-z0-9\s.]/g, " ").replace(/\s+/g, " ").trim()],
    ...(opts?.lyrics?.length ? { lyrics: opts.lyrics } : {}),
  };
}

